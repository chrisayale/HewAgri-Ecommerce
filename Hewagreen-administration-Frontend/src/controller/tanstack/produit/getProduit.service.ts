import apiRequest from "@/controller/api/config/config";
import { auth, produit } from "@/controller/api/constant/apiLink";
import { ProduitCredentials, ResponseAddRole, ResponseProduit_ } from "@/types";

import axios from "axios";

export const _produit = async (
  itemToke: string
): Promise<ResponseProduit_ | undefined> => {
  try {
    const response = await apiRequest<ResponseProduit_ | undefined>({
      method: "GET",
      endpoint: `${auth?.getProduit()}`,
      token: itemToke,
    });
    return response?.data;
  } catch (error) {
    if (axios.isAxiosError(error)) {
      if (error.response) {
        throw new Error(
          error.response.data.message || "Erreur lors de l'authentification"
        );
      } else if (error.request) {
        throw new Error(
          "Le serveur n'a pas répondu. Veuillez réessayer plus tard."
        );
      }
    }
    throw new Error("Une erreur est survenue. Veuillez réessayer.");
  }
};

