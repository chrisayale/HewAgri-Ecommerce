import apiRequest from "@/controller/api/config/config";
import { auth, commandes } from "@/controller/api/constant/apiLink";
import { ResponseCmdTransaction, ResponseCommandes } from "@/types";

import axios from "axios";

export const _commandes = async (
  itemToke: string
): Promise<ResponseCommandes | undefined> => {
  try {
    const response = await apiRequest<ResponseCommandes | undefined>({
      method: "GET",
      endpoint: `${auth?.getCommandes()}`,
      token: itemToke,
    });
    return response?.data;
  } catch (error) {
    if (axios.isAxiosError(error)) {
      if (error.response) {
        throw new Error(
          error.response.data.message || "Erreur des chargements"
        );
      } else if (error.request) {
        throw new Error(
          "Le serveur n'a pas répondu. Veuillez réessayer plus tard."
        );
      }
    }
    throw new Error("Une erreur est survenue. Veuillez réessayer.");
  }
};

