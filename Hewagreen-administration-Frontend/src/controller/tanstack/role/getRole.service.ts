import apiRequest from "@/controller/api/config/config";
import { auth, role } from "@/controller/api/constant/apiLink";
import { ResponseAddRole, ResponseRole, RoleCredentials, RoleCredentialsUpdated } from "@/types";
import axios from "axios";

export const _roles = async (
  itemToke: string
): Promise<ResponseRole | undefined> => {
  try {
    const response = await apiRequest<ResponseRole | undefined>({
      method: "GET",
      endpoint: `${auth?.getRole()}`,
      token: itemToke,
    });
    return response?.data;
  } catch (error) {
    if (axios.isAxiosError(error)) {
      if (error.response) {
        throw new Error(
          error.response.data.message || "Erreur lors de l'authentification"
        );
      } else if (error.request) {
        throw new Error(
          "Le serveur n'a pas répondu. Veuillez réessayer plus tard."
        );
      }
    }
    throw new Error("Une erreur est survenue. Veuillez réessayer.");
  }
};

