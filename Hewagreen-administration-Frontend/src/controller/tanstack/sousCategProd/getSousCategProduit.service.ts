import apiRequest from "@/controller/api/config/config";
import { auth, sousCategorieProduit } from "@/controller/api/constant/apiLink";
import { ResponseAddCategorieCooperative, ResponseSousCategoriProduit, SousCategorieCredentials } from "@/types";

import axios from "axios";

export const _sousCategorieProduit = async (
  itemToke: string
): Promise<ResponseSousCategoriProduit | undefined> => {
  try {
    const response = await apiRequest<ResponseSousCategoriProduit | undefined>({
      method: "GET",
      endpoint: `${auth?.getSousCategProduit()}`,
      token: itemToke,
    });
    return response?.data;
  } catch (error) {
    if (axios.isAxiosError(error)) {
      if (error.response) {
        throw new Error(
          error.response.data.message || "Erreur des chargements"
        );
      } else if (error.request) {
        throw new Error(
          "Le serveur n'a pas répondu. Veuillez réessayer plus tard."
        );
      }
    }
    throw new Error("Une erreur est survenue. Veuillez réessayer.");
  }
};

