import apiRequest from "@/controller/api/config/config";
import { auth, identification } from "@/controller/api/constant/apiLink";
import {
  AddorDeleteRoleUser,
  IdentificationCredentials,
  ResponseAddRole,
  ResponseIdentification,
} from "@/types";
import axios from "axios";

export const _identification = async (
  itemToke: string
): Promise<ResponseIdentification | undefined> => {
  try {
    const response = await apiRequest<ResponseIdentification | undefined>({
      method: "GET",
      endpoint: `${auth?.getUseIdentification()}`,
      token: itemToke,
    });
    return response?.data;
  } catch (error) {
    if (axios.isAxiosError(error)) {
      if (error.response) {
        throw new Error(
          error.response.data.message || "Erreur lors de l'authentification"
        );
      } else if (error.request) {
        throw new Error(
          "Le serveur n'a pas répondu. Veuillez réessayer plus tard."
        );
      }
    }
    throw new Error("Une erreur est survenue. Veuillez réessayer.");
  }
};

